def load_model(model_name, checkpoint_path, device):
    """Load model and return (model, model_type_tag)."""
    from src.nsnet.utils.options import add_model_options
    from src.nsnet.models.nsnet import NSNet
    from src.nsnet.models.arienet import ArieNet

    if model_name == "NSNet":
        import argparse as _ap
        p = _ap.ArgumentParser()
        add_model_options(p)
        opts = p.parse_args([])
        opts.model = "NSNet"
        opts.device = device
        opts.task = "satisfiability"
        model = NSNet(opts)
        ckpt = torch.load(checkpoint_path, map_location=device)
        model.load_state_dict(ckpt["state_dict"], strict=False)

    elif model_name == "ArieNet":
        import argparse as _ap
        p = _ap.ArgumentParser()
        add_model_options(p)
        opts = p.parse_args([])
        opts.model = "ArieNet"
        opts.device = device
        opts.task = "satisfiability"
        model = ArieNet(opts)
        ckpt = torch.load(checkpoint_path, map_location=device)
        model.load_state_dict(ckpt["state_dict"], strict=False)

    elif is_backbone_model(model_name):
        from train_arienet_backbone import ArieNetBackbone
        ckpt = torch.load(checkpoint_path, map_location=device)
        ckpt_args = ckpt.get("args", {})
        no_lsp = ckpt_args.get("no_precomputed_local_sat", False)
        model = ArieNetBackbone(device=device, no_precomputed_local_sat=no_lsp)
        model.load_state_dict(ckpt["model_state_dict"], strict=False)

    elif model_name == "BackboneCanonical":
        from train_arienet_backbone import ArieNetBackbone
        model = ArieNetBackbone(device=device, use_subgraph_features=True, subgraph_dim=32)
        ckpt = torch.load(checkpoint_path, map_location=device)
        model.load_state_dict(ckpt["model_state_dict"], strict=False)

    elif model_name == "BackboneUP":
        from train_arienet_backbone import ArieNetBackbone
        model = ArieNetBackbone(device=device, use_up_features=True)
        ckpt = torch.load(checkpoint_path, map_location=device)
        model.load_state_dict(ckpt["model_state_dict"], strict=False)

    elif is_cooc_model(model_name):
        from src.nsnet.models.arienet import ArieNetCooc
        import argparse as _ap
        ckpt = torch.load(checkpoint_path, map_location=device)
        ckpt_args = ckpt["args"]
        cooc_opts = _ap.Namespace(
            dim=ckpt_args.dim,
            n_rounds=ckpt_args.n_rounds,
            n_mlp_layers=ckpt_args.n_mlp_layers,
            activation="relu",
            device=device,
            task="satisfiability",
        )
        model = ArieNetCooc(cooc_opts)
        model.load_state_dict(ckpt["model_state_dict"])

    elif is_rlaf_model(model_name):
        import sys as _sys
        _sys.path.insert(0, os.path.join(os.path.dirname(__file__), "src"))
        from omegaconf import OmegaConf
        from nsnet.models.arienet_rlaf import ArieNetRLAF, ArieNetRLAFCooc
        # Load config.yaml from the checkpoint directory if present
        ckpt_dir = os.path.dirname(os.path.abspath(checkpoint_path))
        cfg_file = os.path.join(ckpt_dir, "config.yaml")
        cfg = OmegaConf.load(cfg_file) if os.path.exists(cfg_file) else None
        model_kwargs = dict(dim=128, n_rounds=26, n_mlp_layers=3)
        use_cooc = False
        if cfg is not None:
            model_kwargs["dim"] = cfg.model.dim
            model_kwargs["n_rounds"] = cfg.model.n_rounds
            model_kwargs["n_mlp_layers"] = cfg.model.n_mlp_layers
            model_kwargs["no_precomputed_local_sat"] = cfg.model.no_precomputed_local_sat
            model_kwargs["use_up_features"] = cfg.model.use_up_features
            use_cooc = getattr(cfg, "use_cooc", False)
        ModelCls = ArieNetRLAFCooc if use_cooc else ArieNetRLAF
        model = ModelCls(**model_kwargs)
        model.load_state_dict(torch.load(checkpoint_path, map_location=device))

    else:
        raise ValueError(f"Unknown model: {model_name}")

    model.to(device)
    model.eval()
    return model


def build_dataloader(model_name, cnf_dir, batch_size, num_workers, cooc_process_workers=1,
                     backbone_process_workers=4):
    """Return (dataloader, list_of_cnf_files)."""
    if model_name in ("NSNet", "ArieNet"):
        from src.nsnet.utils.dataloader import get_dataloader
        import argparse as _ap
        from src.nsnet.utils.options import add_model_options

        p = _ap.ArgumentParser()
        add_model_options(p)
        opts = p.parse_args([])
        opts.model = model_name
        opts.device = torch.device("cpu")
        opts.task = "satisfiability"
        opts.batch_size = batch_size
        opts.num_workers = num_workers
        opts.pin_memory = False
        opts.test_dir = cnf_dir

        loader = get_dataloader(cnf_dir, opts, "test")
        files = sorted(glob.glob(os.path.join(cnf_dir, "*.cnf")))
        return loader, [os.path.abspath(f) for f in files]

    elif is_backbone_model(model_name):
        from train_arienet_backbone import BackboneBPGDataset
        dataset = BackboneBPGDataset(cnf_dir, num_process_workers=backbone_process_workers)
        loader = DataLoader(dataset, batch_size=batch_size, shuffle=False,
                            num_workers=num_workers, pin_memory=False)
        return loader, [os.path.abspath(f) for f in dataset.cnf_files]

    elif model_name == "BackboneCanonical":
        from train_arienet_backbone_canonical import CanonicalBackboneBPGDataset
        # compute_subgraphs=False: the canonical subgraph feature computation runs a
        # brute-force 2^k truth-table enumeration per BPG edge (k = size of 2-hop
        # neighbourhood, easily 10-20 vars for OOD instances).  That makes processing
        # infeasibly slow for large n.  With compute_subgraphs=False the BPG is still
        # built correctly; the model's subgraph branch is simply skipped (it guards
        # with `if hasattr(data, 'subgraphs_p1') and data.subgraphs_p1 is not None`).
        # This means BackboneCanonical runs as a plain Backbone for OOD evaluation.
        dataset = CanonicalBackboneBPGDataset(cnf_dir, compute_subgraphs=False)
        loader = DataLoader(dataset, batch_size=batch_size, shuffle=False,
                            num_workers=num_workers, pin_memory=False)
        return loader, [os.path.abspath(f) for f in dataset.cnf_files]

    elif model_name == "BackboneUP":
        from train_arienet_backbone import BackboneBPGDataset
        # use_up_features=True triggers per-literal UP feature precomputation via pysat.
        # Backbone labels (backbones.pkl) are not needed for inference; the dataset
        # handles a missing backbones.pkl gracefully (warns, sets all y=2).
        # Default to single-threaded to avoid pysat C-extension deadlocks under fork.
        dataset = BackboneBPGDataset(cnf_dir, use_up_features=True,
                                     num_process_workers=backbone_process_workers)
        loader = DataLoader(dataset, batch_size=batch_size, shuffle=False,
                            num_workers=num_workers, pin_memory=False)
        return loader, [os.path.abspath(f) for f in dataset.cnf_files]

    elif is_cooc_model(model_name):
        from train_arienet_cooc import CoocBPGDataset
        dataset = CoocBPGDataset(cnf_dir, process_workers=cooc_process_workers)
        loader = DataLoader(dataset, batch_size=batch_size, shuffle=False,
                            num_workers=num_workers, pin_memory=False)
        return loader, [os.path.abspath(f) for f in dataset.cnf_files]

    elif is_rlaf_model(model_name):
        import sys as _sys
        _sys.path.insert(0, os.path.join(os.path.dirname(__file__), "src"))
        from nsnet.datasets.rlaf_dataset import RLAFBPGDataset, _collate_skip_none
        dataset = RLAFBPGDataset(
            path=cnf_dir,
            num_workers=backbone_process_workers,
        )
        loader = DataLoader(dataset, batch_size=batch_size, shuffle=False,
                            num_workers=num_workers, pin_memory=False,
                            collate_fn=_collate_skip_none)
        return loader, [os.path.abspath(f) for f in dataset.cnf_files]

    else:
        raise ValueError(f"Unknown model: {model_name}")


def run_inference(model, model_name, loader, device):
    """
    Run the model over the full dataloader.
    Returns list of np.ndarray [n_vars] with phase hints (0 or 1).
    RLAF models should use run_rlaf_inference instead.
    """
    phase_hints_list = []

    for data in loader:
        data = data.to(device)
        with torch.no_grad():
            if model_name in ("Backbone", "BackboneCanonical", "BackboneUP") or is_backbone_model(model_name):
                v_logits = model(data)
                v_probs = F.softmax(v_logits, dim=1)
            else:
                v_probs = model(data)  # already softmax

        # Determine v_sizes per graph in batch.
        # ArieNet uses BPG → data.n_literals ; NSNet uses OldBPG → data.l_size
        # Backbone, BackboneCanonical and ArieNetCooc also use BPG → data.n_literals
        if model_name in ("ArieNet", "Backbone", "BackboneCanonical", "BackboneUP") or is_backbone_model(model_name) or is_cooc_model(model_name):
            raw = data.n_literals
            if isinstance(raw, torch.Tensor):
                v_sizes = (raw / 2).int().tolist()
            elif isinstance(raw, list):
                v_sizes = [int(n / 2) for n in raw]
            else:
                v_sizes = [int(raw / 2)]
        elif model_name == "NSNet":
            raw = data.l_size
            if isinstance(raw, torch.Tensor):
                v_sizes = (raw / 2).int().tolist()
            elif isinstance(raw, list):
                v_sizes = [int(n / 2) for n in raw]
            else:
                v_sizes = [int(raw / 2)]
        else:
            raise ValueError(f"Unknown model: {model_name}")

        offset = 0
        for v_size in v_sizes:
            probs = v_probs[offset : offset + v_size].cpu().numpy()
            phase = (probs[:, 1] > probs[:, 0]).astype(float)
            phase_hints_list.append(phase)
            offset += v_size

    return phase_hints_list


def run_rlaf_inference(model, loader, device, scale_sigma=0.1):
    """Run an RLAF model and return var_params as list of np.ndarray [n_vars, 2].

    Uses the modal (deterministic) policy: phase = sign(rho), weight = exp(mu).
    Column 0 = rho (phase logit), column 1 = weight (log-normal mean).
    """
    import sys as _sys
    _sys.path.insert(0, os.path.join(os.path.dirname(__file__), "src"))
    from nsnet.policy import policy_bpg as policy

    var_params_list = []
    model.eval()
    with torch.no_grad():
        for data in loader:
            if data is None:
                continue
            data = data.to(device)
            y_var = model(data)  # [total_vars_in_batch, 2]

            n_lits = data.n_literals
            if isinstance(n_lits, torch.Tensor):
                n_vars_list = (n_lits // 2).int().tolist()
            elif isinstance(n_lits, list):
                n_vars_list = [int(n // 2) for n in n_lits]
            else:
                n_vars_list = [int(n_lits // 2)]

            # Modal var_params: shape [1, total_vars, 2] → squeeze
            params_modal = policy.mode(y_var.float(), scale_sigma=scale_sigma).squeeze(0)
            params_np = params_modal.cpu().numpy()

            offset = 0
            for n_v in n_vars_list:
                var_params_list.append(params_np[offset:offset + n_v])
                offset += n_v

    return var_params_list


