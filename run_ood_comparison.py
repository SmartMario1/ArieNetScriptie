"""
OOD Benchmark Comparison Script

Tests multiple GNN models as unweighted (constant weight 1.0) guidance for the march solver
across size buckets generated by generate_ood_benchmark.py.

For each size bucket and each model:
  - Runs inference + solving on all problems in the bucket
  - If 5 consecutive timeouts occur → skip the rest of that bucket for that model
  - Records per-bucket per-model: num_solved, num_timed_out, num_skipped, avg_decisions, avg_time

Output: a single JSON file with nested structure:
    results[size_folder][model_name] = { num_solved, num_timed_out, num_skipped,
                                         avg_decisions, avg_time, total_problems }

Usage:
    python run_ood_comparison.py SATSolving/3-sat/ood_test \\
        --arienet_checkpoint runs/sat_arienet_3-sat_marginal_on_4000/checkpoints/model_best.pt \\
        --nsnet_checkpoint   runs/sat_nsnet_3-sat_marginal_on_4000/checkpoints/model_best.pt  \\
        --canonical_checkpoint models/arienet_backbone_canonical/best_model.pt                 \\
        --cooc_checkpoint      models/arienet_cooc/best_model.pt                                \\
        --extra_cooc_checkpoint ArieNetCoocA=models/arienet_cooc_a/best_model.pt                \\
        "--extra_cooc_checkpoint ArieNetCoocB=models/arienet_cooc_b/best_model.pt \\\n        --extra_backbone_checkpoint BackboneNoLSP=models/arienet_backbone_nolsp/best_model.pt \\\n        --extra_backbone_checkpoint BackboneWithLSP=models/arienet_backbone/best_model.pt
"""

