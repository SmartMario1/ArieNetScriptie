def evaluate_bucket(model, model_name, cnf_dir, batch_size, num_workers,
                    device, timeout, seed, consecutive_timeout_limit,
                    cooc_process_workers=1, backbone_process_workers=4):
    """
    Run one model on one size bucket.
    Returns dict: num_solved, num_timed_out, num_skipped, avg_decisions, avg_time, total_problems
    """
    print(f"    Building dataloader for {model_name} ...")
    try:
        loader, all_files = build_dataloader(
            model_name, cnf_dir, batch_size, num_workers,
            cooc_process_workers=cooc_process_workers,
            backbone_process_workers=backbone_process_workers,
        )
    except Exception as e:
        print(f"    [ERROR] Could not build dataloader: {e}")
        return None

    n_total = len(all_files)
    if n_total == 0:
        print(f"    [WARN] No CNF files found in {cnf_dir}")
        return None

    print(f"    Running inference on {n_total} instances ...")
    try:
        if is_rlaf_model(model_name):
            guidance_list = run_rlaf_inference(model, loader, device)
        else:
            guidance_list = run_inference(model, model_name, loader, device)
    except Exception as e:
        print(f"    [ERROR] Inference failed: {e}")
        return None

    assert len(guidance_list) == n_total, (
        f"Mismatch: {len(guidance_list)} predictions vs {n_total} files"
    )

    solve_mode = "weighted (RLAF)" if is_rlaf_model(model_name) else "unweighted"
    print(f"    Solving with march ({solve_mode} guidance, timeout={timeout}s) ...")
    num_solved = 0
    num_timed_out = 0
    num_skipped = 0
    decisions_list = []
    times_list = []

    consecutive_timeouts = 0

    for idx, (filepath, guidance) in enumerate(zip(all_files, guidance_list)):
        # Check consecutive timeout early-exit
        if consecutive_timeouts >= consecutive_timeout_limit:
            remaining = n_total - idx
            num_skipped += remaining
            print(f"    [{idx}/{n_total}] {consecutive_timeout_limit} consecutive timeouts — "
                  f"skipping remaining {remaining} instances.")
            break

        clauses, num_vars = load_dimacs_cnf(filepath)
        t_start = time.time()
        if is_rlaf_model(model_name):
            stats = solve_with_march_weighted(clauses, num_vars, guidance, seed, timeout)
        else:
            stats = solve_with_march_unweighted(clauses, num_vars, guidance, seed, timeout)
        wall_time = time.time() - t_start

        result = stats.get("Result", "UNKNOWN")

        if result == "SATISFIABLE":
            num_solved += 1
            consecutive_timeouts = 0
        elif result == "TIMEOUT":
            num_timed_out += 1
            consecutive_timeouts += 1
        else:
            # UNSATISFIABLE or UNKNOWN — count as solved (decided), reset streak
            num_solved += 1
            consecutive_timeouts = 0

        dec = stats.get("decisions", -1)
        cpu_t = stats.get("CPU_time", -1.0)
        if dec > 0:
            decisions_list.append(dec)
        # Use wall time if solver didn't report CPU time
        times_list.append(cpu_t if cpu_t > 0 else wall_time)

        if (idx + 1) % 10 == 0 or (idx + 1) == n_total:
            print(f"    [{idx + 1}/{n_total}] solved={num_solved} "
                  f"timed_out={num_timed_out} skipped={num_skipped}", end="\r")

    print()  # newline after \r progress

    return {
        "total_problems": n_total,
        "num_solved": num_solved,
        "num_timed_out": num_timed_out,
        "num_skipped": num_skipped,
        "avg_decisions": float(np.mean(decisions_list)) if decisions_list else None,
        "avg_time": float(np.mean(times_list)) if times_list else None,
    }


