def parse_extra_backbone_args(extra_args):
    """
    Parse repeatable --extra_backbone_checkpoint values.
    Accepted formats:
      - NAME=PATH
      - PATH  (auto-named as Backbone_2, Backbone_3, ...)
    Returns dict model_name -> checkpoint_path.
    """
    extra_map = {}
    next_idx = 2

    for raw in extra_args or []:
        item = raw.strip()
        if not item:
            continue

        if "=" in item:
            name, path = item.split("=", 1)
            name = name.strip()
            path = path.strip()
            if not name:
                raise ValueError(f"Invalid --extra_backbone_checkpoint '{raw}': empty model name")
            if name in extra_map:
                raise ValueError(f"Duplicate extra backbone model name: {name}")
            extra_map[name] = path
        else:
            while True:
                auto_name = f"Backbone_{next_idx}"
                next_idx += 1
                if auto_name not in extra_map:
                    break
            extra_map[auto_name] = item

    return extra_map


