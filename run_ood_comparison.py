def evaluate_bucket_unmodified(cnf_dir, timeout, consecutive_timeout_limit):
    """
    Run the unmodified march solver on every CNF file in cnf_dir with no GNN
    guidance (pure solver baseline).
    Returns the same dict shape as evaluate_bucket().
    """
    all_files = sorted(glob.glob(os.path.join(cnf_dir, "*.cnf")))
    n_total = len(all_files)
    if n_total == 0:
        print(f"    [WARN] No CNF files found in {cnf_dir}")
        return None

    print(f"    Solving {n_total} instances with unmodified march (timeout={timeout}s) ...")

    num_solved = 0
    num_timed_out = 0
    num_skipped = 0
    decisions_list = []
    times_list = []
    consecutive_timeouts = 0

    for idx, filepath in enumerate(all_files):
        if consecutive_timeouts >= consecutive_timeout_limit:
            remaining = n_total - idx
            num_skipped += remaining
            print(f"    [{idx}/{n_total}] {consecutive_timeout_limit} consecutive timeouts — "
                  f"skipping remaining {remaining} instances.")
            break

        t_start = time.time()
        stats = solve_with_march_unmodified(os.path.abspath(filepath), timeout)
        wall_time = time.time() - t_start

        result = stats.get("Result", "UNKNOWN")
        if result == "TIMEOUT":
            num_timed_out += 1
            consecutive_timeouts += 1
        else:
            num_solved += 1
            consecutive_timeouts = 0

        dec = stats.get("decisions", -1)
        cpu_t = stats.get("CPU_time", -1.0)
        if dec > 0:
            decisions_list.append(dec)
        times_list.append(cpu_t if cpu_t > 0 else wall_time)

        if (idx + 1) % 10 == 0 or (idx + 1) == n_total:
            print(f"    [{idx + 1}/{n_total}] solved={num_solved} "
                  f"timed_out={num_timed_out} skipped={num_skipped}", end="\r")

    print()

    return {
        "total_problems": n_total,
        "num_solved": num_solved,
        "num_timed_out": num_timed_out,
        "num_skipped": num_skipped,
        "avg_decisions": float(np.mean(decisions_list)) if decisions_list else None,
        "avg_time": float(np.mean(times_list)) if times_list else None,
    }


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="OOD benchmark: test models on increasingly large 3-SAT instances."
    )
    parser.add_argument(
        "ood_dir",
        type=str,
        help="Root OOD benchmark directory (e.g. SATSolving/3-sat/ood_test)",
    )

    # Model checkpoints (all optional — models without checkpoints are skipped)
    parser.add_argument("--nsnet_checkpoint", type=str, default=None,
                        help="Path to NSNet checkpoint")
    parser.add_argument("--arienet_checkpoint", type=str, default=None,
                        help="Path to ArieNet checkpoint")
    parser.add_argument("--backbone_checkpoint", type=str, default=None,
                        help="Path to plain ArieNetBackbone checkpoint (supports "
                             "--no_precomputed_local_sat checkpoints via saved args)")
    parser.add_argument(
        "--extra_backbone_checkpoint",
        action="append",
        default=[],
        help=(
            "Additional Backbone model checkpoint. Repeatable. Formats: "
            "NAME=PATH or PATH (auto-named Backbone_2, Backbone_3, ...). "
            "Useful to compare e.g. a model trained with and without "
            "--no_precomputed_local_sat side by side."
        ),
    )
    parser.add_argument("--canonical_checkpoint", type=str, default=None,
                        help="Path to BackboneCanonical checkpoint")
    parser.add_argument("--backbone_up_checkpoint", type=str, default=None,
                        help="Path to BackboneUP checkpoint (ArieNetBackbone trained with "
                             "--use_up_features; requires python-sat at inference time)")
    parser.add_argument("--cooc_checkpoint", type=str, default=None,
                        help="Path to ArieNetCooc checkpoint")
    parser.add_argument(
        "--extra_cooc_checkpoint",
        action="append",
        default=[],
        help=(
            "Additional CoOC model checkpoint. Repeatable. Formats: "
            "NAME=PATH or PATH (auto-named ArieNetCooc_2, ArieNetCooc_3, ...)."
        ),
    )
    parser.add_argument(
        "--rlaf_checkpoint",
        action="append",
        default=[],
        help=(
            "RLAF model checkpoint (ArieNetRLAF / ArieNetRLAFCooc trained with "
            "train_arienet_rlaf.py). Repeatable. Formats: "
            "NAME=PATH or PATH (auto-named RLAF, RLAF_2, ...). "
            "Uses march_weighted with full phase+weight guidance."
        ),
    )
    parser.add_argument("--march_unmodified", action="store_true", default=False,
                        help="Include unmodified march solver as a baseline (no GNN guidance)")
    parser.add_argument("--march_unmodified_path", type=str, default=None,
                        help="Override path to unmodified march binary")

    # Solver / runtime settings
    parser.add_argument("--timeout", type=int, default=300,
                        help="Per-instance solver timeout in seconds (default: 300 = 5 min)")
    parser.add_argument("--consecutive_timeout_limit", type=int, default=5,
                        help="Skip rest of size bucket after this many consecutive timeouts (default: 5)")
    parser.add_argument("--seed", type=int, default=1,
                        help="Random seed for the solver (default: 1)")
    parser.add_argument("--batch_size", type=int, default=1,
                        help="Batch size for GNN inference (default: 1; increase for small instances)")
    parser.add_argument("--num_workers", type=int, default=0,
                        help="DataLoader workers (default: 0)")
    parser.add_argument("--cooc_process_workers", type=int, default=1,
                        help="CoOC dataset preprocessing workers (default: 1; safer on WSL)")
    parser.add_argument("--backbone_process_workers", type=int, default=1,
                        help="Backbone/BackboneUP dataset preprocessing workers (default: 1; "
                             "set to 1 to avoid pysat C-extension deadlocks under fork)")
    parser.add_argument("--march_path", type=str, default=None,
                        help="Override path to march_nh binary")

    # Output
    parser.add_argument("--out_file", type=str, default=None,
                        help="Output JSON file path (default: auto-timestamped)")

    args = parser.parse_args()

    # Override march paths if requested
    if args.march_path:
        global MARCH_UNWEIGHTED_PATH
        MARCH_UNWEIGHTED_PATH = args.march_path
    if args.march_unmodified_path:
        global MARCH_UNMODIFIED_PATH
        MARCH_UNMODIFIED_PATH = args.march_unmodified_path

    # Build list of (model_name, checkpoint_path) to run
    model_ckpts = {
        "NSNet": args.nsnet_checkpoint,
        "ArieNet": args.arienet_checkpoint,
        "Backbone": args.backbone_checkpoint,
        "BackboneCanonical": args.canonical_checkpoint,
        "BackboneUP": args.backbone_up_checkpoint,
        "ArieNetCooc": args.cooc_checkpoint,
    }

    try:
        extra_cooc_models = parse_extra_cooc_args(args.extra_cooc_checkpoint)
    except ValueError as e:
        print(f"[ERROR] {e}")
        sys.exit(1)

    try:
        extra_backbone_models = parse_extra_backbone_args(args.extra_backbone_checkpoint)
    except ValueError as e:
        print(f"[ERROR] {e}")
        sys.exit(1)

    try:
        rlaf_models = parse_rlaf_args(args.rlaf_checkpoint)
    except ValueError as e:
        print(f"[ERROR] {e}")
        sys.exit(1)

    overlapping = set(model_ckpts).intersection(extra_cooc_models).union(
        set(model_ckpts).intersection(extra_backbone_models),
        set(extra_cooc_models).intersection(extra_backbone_models),
        set(rlaf_models).intersection(model_ckpts),
        set(rlaf_models).intersection(extra_cooc_models),
        set(rlaf_models).intersection(extra_backbone_models),
    )
    if overlapping:
        print("[ERROR] Duplicate model names across built-in / extra CoOC / extra Backbone / RLAF: "
              f"{sorted(overlapping)}")
        sys.exit(1)

    model_ckpts.update(extra_cooc_models)
    model_ckpts.update(extra_backbone_models)
    model_ckpts.update(rlaf_models)

    # Register extra backbone names so is_backbone_model() recognises them.
    _EXTRA_BACKBONE_NAMES.update(extra_backbone_models.keys())
    # Register RLAF model names so is_rlaf_model() recognises them.
    _RLAF_MODEL_NAMES.update(rlaf_models.keys())

    active_models = {k: v for k, v in model_ckpts.items() if v is not None}
    if args.march_unmodified:
        active_models["MarchUnmodified"] = "(no checkpoint)"

    if not active_models:
        print("[ERROR] No model checkpoints provided. Use --nsnet_checkpoint, "
              "--arienet_checkpoint, --canonical_checkpoint, --cooc_checkpoint, "
              "or --march_unmodified.")
        sys.exit(1)

    # Discover size buckets (sorted by variable count)
    ood_dir = os.path.abspath(args.ood_dir)
    buckets = sorted(
        [d for d in os.listdir(ood_dir) if os.path.isdir(os.path.join(ood_dir, d))],
        key=lambda x: int(x.lstrip("n")) if x.lstrip("n").isdigit() else 0,
    )
    if not buckets:
        print(f"[ERROR] No size bucket folders found in {ood_dir}")
        sys.exit(1)

    print("=" * 70)
    print("OOD BENCHMARK COMPARISON")
    print("=" * 70)
    print(f"  OOD dir          : {ood_dir}")
    print(f"  Size buckets     : {buckets}")
    print(f"  Models           : {list(active_models.keys())}")
    print(f"  Timeout          : {args.timeout}s per instance")
    print(f"  Consec. timeout  : skip after {args.consecutive_timeout_limit}")
    print(f"  Seed             : {args.seed}")
    print("=" * 70)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"  Device           : {device}\n")

    # Results structure: results[bucket][model_name] = {...}
    results = {
        "timestamp": datetime.now().isoformat(),
        "ood_dir": ood_dir,
        "timeout": args.timeout,
        "consecutive_timeout_limit": args.consecutive_timeout_limit,
        "seed": args.seed,
        "models": list(active_models.keys()),
        "checkpoints": active_models,
        "sizes": {},
    }

    # Pre-load all models once (avoids repeated checkpoint loading)
    print("Loading models...")
    loaded_models = {}
    for model_name, ckpt_path in active_models.items():
        if model_name == "MarchUnmodified":
            loaded_models[model_name] = "__unmodified_march__"
            print(f"  ✓ MarchUnmodified (no GNN, direct solver baseline)")
            continue
        print(f"  Loading {model_name} from {ckpt_path} ...")
        try:
            loaded_models[model_name] = load_model(model_name, ckpt_path, device)
            print(f"  ✓ {model_name} loaded")
        except Exception as e:
            print(f"  ✗ {model_name} FAILED to load: {e}")
            loaded_models[model_name] = None
    print()

    # Determine output file
    if args.out_file is None:
        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        args.out_file = f"ood_results_{ts}.json"

    # -----------------------------------------------------------------------
    # Main loop: iterate buckets × models
    # -----------------------------------------------------------------------
    for bucket in buckets:
        bucket_dir = os.path.join(ood_dir, bucket)
        cnf_count = len(glob.glob(os.path.join(bucket_dir, "*.cnf")))
        print(f"\n{'='*70}")
        print(f"SIZE BUCKET: {bucket}  ({cnf_count} CNF files)")
        print(f"{'='*70}")

        results["sizes"][bucket] = {}

        for model_name, model in loaded_models.items():
            if model is None:
                print(f"  [{model_name}] Skipped (failed to load).")
                results["sizes"][bucket][model_name] = {"error": "model load failed"}
                continue

            print(f"\n  >> {model_name}")
            t_bucket_start = time.time()

            if model_name == "MarchUnmodified":
                bucket_result = evaluate_bucket_unmodified(
                    cnf_dir=bucket_dir,
                    timeout=args.timeout,
                    consecutive_timeout_limit=args.consecutive_timeout_limit,
                )
            else:
                bucket_result = evaluate_bucket(
                    model=model,
                    model_name=model_name,
                    cnf_dir=bucket_dir,
                    batch_size=args.batch_size,
                    num_workers=args.num_workers,
                    device=device,
                    timeout=args.timeout,
                    seed=args.seed,
                    consecutive_timeout_limit=args.consecutive_timeout_limit,
                    cooc_process_workers=args.cooc_process_workers,
                    backbone_process_workers=args.backbone_process_workers,
                )

            t_bucket = time.time() - t_bucket_start

            if bucket_result is None:
                results["sizes"][bucket][model_name] = {"error": "evaluation failed"}
                print(f"  [{model_name}] Evaluation failed.")
            else:
                bucket_result["bucket_wall_time"] = round(t_bucket, 2)
                results["sizes"][bucket][model_name] = bucket_result

                print(f"  [{model_name}] Done in {t_bucket:.1f}s | "
                      f"solved={bucket_result['num_solved']} "
                      f"timed_out={bucket_result['num_timed_out']} "
                      f"skipped={bucket_result['num_skipped']} | "
                      f"avg_dec={bucket_result['avg_decisions']} "
                      f"avg_time={bucket_result['avg_time']}")

        # Save after every bucket so results aren't lost
        with open(args.out_file, "w") as f:
            json.dump(results, f, indent=2)
        print(f"\n  [Saved intermediate results to {args.out_file}]")

    # -----------------------------------------------------------------------
    # Final summary
    # -----------------------------------------------------------------------
    print("\n\n" + "=" * 70)
    print("FINAL SUMMARY")
    print("=" * 70)
    header = f"{'Bucket':<12}" + "".join(f"{m:<22}" for m in active_models)
    print(header)
    print("-" * len(header))

    for bucket in buckets:
        row = f"{bucket:<12}"
        for model_name in active_models:
            r = results["sizes"][bucket].get(model_name, {})
            if "error" in r:
                row += f"{'ERROR':<22}"
            elif r:
                row += f"{r['num_solved']}S/{r['num_timed_out']}T/{r['num_skipped']}SK  "
            else:
                row += f"{'N/A':<22}"
        print(row)

    print(f"\nFull results saved to: {args.out_file}")
    print("=" * 70)


if __name__ == "__main__":
    main()
