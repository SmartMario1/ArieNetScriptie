def _parse_march(stdout):
    stats = {"Result": "UNKNOWN", "decisions": -1, "CPU_time": -1.0}
    for line in stdout.splitlines():
        line = line.strip()
        upper = line.upper()
        if "SATISFIABLE" in upper and "UNSATISFIABLE" not in upper:
            stats["Result"] = "SATISFIABLE"
        elif "UNSATISFIABLE" in upper:
            stats["Result"] = "UNSATISFIABLE"
        if line.startswith("c decisions"):
            try:
                stats["decisions"] = int(line.split(":")[1].strip().split()[0])
            except (IndexError, ValueError):
                pass
        if "time" in line.lower() and ":" in line:
            try:
                stats["CPU_time"] = float(line.split(":")[1].strip().split()[0])
            except (IndexError, ValueError):
                pass
    return stats


